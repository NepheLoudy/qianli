/**
 * gcode 机型指纹提取单测（2026-11-06 跨品牌误派 P0 修复）
 * 背景：拓竹系切片（Orca/Bambu Studio）导出的 .gcode 头部带 `; printer_model`——
 * 此前不提取导致提交链 embeddedParams=null，学习选机按「.gcode=闪铸」扩展名瞎兜底，
 * 把 H2D 切片派给闪铸 A5P 打出废件（R20261106-001 实案）。
 * 用法：node test/stub-test-gcode-meta.js
 */
const assert = require('assert');
const { extractGcodeMeta } = require('../src/services/slicerExtract');

let pass = 0;
let failures = 0;
function check(name, fn) {
  try {
    fn();
    pass++;
    console.log(`✓ ${name}`);
  } catch (err) {
    failures++;
    console.error(`✗ ${name} — ${err.message}`);
  }
}

// 今天实单（R20261106-001）头部同款样式
const ORCA_H2D_HEAD = [
  '; HEADER_BLOCK_START',
  '; generated by OrcaSlicer 2.4.2 on 2026-11-06 at 17:47:15',
  '; model printing time: 11m 46s; total estimated time: 17m 23s',
  '; total layer number: 45',
  '; HEADER_BLOCK_END',
  '; CONFIG_BLOCK_START',
  '; printer_model = Bambu Lab H2D',
  '; printer_settings_id = Bambu Lab H2D 0.4 nozzle',
  '; printer_variant = 0.4',
].join('\n');

check('拓竹系 gcode 头部：提取 printer_model + 预估时长', () => {
  const meta = extractGcodeMeta(Buffer.from(ORCA_H2D_HEAD + '\nG28\nM104 S240'));
  assert.strictEqual(meta.machineModel, 'Bambu Lab H2D');
  assert.strictEqual(meta.estMinutes, 17); // 17m 23s → 17 分钟
});

check('无 printer_model 的 gcode（闪铸老样式/外来件）：machineModel=null', () => {
  const ff = [
    '; generated by FlashForge slicer',
    '; estimated printing time (normal mode) = 12m 30s',
    'G28',
  ].join('\n');
  const meta = extractGcodeMeta(Buffer.from(ff));
  assert.strictEqual(meta.machineModel, null);
});

check('指纹在 256KB 窗口外不误读：按无指纹处理；窗口内深处（实单偏移 37KB 场景）能提出', () => {
  const pad = '; x\n' + 'G1 X1 Y1\n'.repeat(60000); // ~400KB，指纹落在窗口外
  const deep = Buffer.from(pad + '; printer_model = Bambu Lab A1 mini\n');
  assert.strictEqual(extractGcodeMeta(deep).machineModel, null);
  const padded = '; pad\n' + 'G1 X1 Y1\n'.repeat(4500) + '; printer_model = Bambu Lab H2D\n'; // ~37KB，窗口内
  assert.strictEqual(extractGcodeMeta(Buffer.from(padded)).machineModel, 'Bambu Lab H2D');
});

process.exit(failures > 0 ? 1 : 0);
